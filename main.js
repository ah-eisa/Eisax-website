// State handling
const isArRoute = window.location.pathname.startsWith("/ar");
const urlParams = new URLSearchParams(window.location.search);
const queryLang = urlParams.get("lang");

let lang = "en";
if (isArRoute) {
  lang = "ar";
} else if (queryLang === "ar" || queryLang === "en") {
  lang = queryLang;
  localStorage.setItem("eisax-lang", lang);
} else {
  lang = localStorage.getItem("eisax-lang") || "en";
}

let theme = localStorage.getItem("eisax-theme") || "dark";

function applyLanguage() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.dir = lang === "ar" ? "rtl" : "ltr";

  // Translate document title & meta tags
  if (i18n[lang]["page.title"]) {
    document.title = i18n[lang]["page.title"];
  }
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && i18n[lang]["page.desc"]) {
    metaDesc.setAttribute("content", i18n[lang]["page.desc"]);
  }

  // Update text for all elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[lang] && i18n[lang][key]) {
      el.textContent = i18n[lang][key];
    }
  });

  // Update language toggle buttons text
  const nextLangText = lang === "en" ? "AR" : "EN";
  const btn = document.getElementById("langToggle");
  const btnMobile = document.getElementById("langToggleMobile");
  if (btn) btn.textContent = nextLangText;
  if (btnMobile) btnMobile.textContent = nextLangText;
}

function applyTheme() {
  document.documentElement.dataset.theme = theme;
  const icon = theme === "dark" ? "◐" : "◑";
  const tBtn = document.getElementById("themeToggle");
  const tBtnMobile = document.getElementById("themeToggleMobile");
  if (tBtn) tBtn.textContent = icon;
  if (tBtnMobile) tBtnMobile.textContent = icon;
}

function toggleLanguage() {
  if (isArRoute) {
    localStorage.setItem("eisax-lang", "en");
    window.location.href = "/" + (window.location.hash || "");
    return;
  }
  localStorage.setItem("eisax-lang", "ar");
  window.location.href = "/ar/" + (window.location.hash || "");
}

function toggleTheme() {
  theme = theme === "dark" ? "light" : "dark";
  localStorage.setItem("eisax-theme", theme);
  applyTheme();
}

// Mobile Drawer Handlers
const mobileDrawer = document.getElementById("mobileDrawer");
const drawerBackdrop = document.getElementById("drawerBackdrop");
const mobileToggle = document.getElementById("mobileToggle");
const closeDrawerBtn = document.getElementById("closeDrawer");

// Initialize drawer accessibility state
if (mobileDrawer) {
  mobileDrawer.setAttribute("aria-hidden", "true");
  mobileDrawer.inert = true;
}

function openDrawer() {
  if (mobileDrawer) {
    mobileDrawer.classList.add("open");
    mobileDrawer.setAttribute("aria-hidden", "false");
    mobileDrawer.inert = false;
    closeDrawerBtn?.focus();
  }
  if (drawerBackdrop) drawerBackdrop.classList.add("open");
  if (mobileToggle) mobileToggle.setAttribute("aria-expanded", "true");
  document.body.style.overflow = "hidden";
}

function closeDrawer(restoreFocus = true) {
  if (mobileDrawer) {
    mobileDrawer.classList.remove("open");
    mobileDrawer.setAttribute("aria-hidden", "true");
    mobileDrawer.inert = true;
  }
  if (drawerBackdrop) drawerBackdrop.classList.remove("open");
  if (mobileToggle) {
    mobileToggle.setAttribute("aria-expanded", "false");
    if (restoreFocus) mobileToggle.focus();
  }
  document.body.style.overflow = "";
}

// Event Listeners
if (mobileToggle) mobileToggle.addEventListener("click", openDrawer);
if (closeDrawerBtn) closeDrawerBtn.addEventListener("click", () => closeDrawer(true));
if (drawerBackdrop) drawerBackdrop.addEventListener("click", () => closeDrawer(true));

// Close drawer on clicking mobile nav links
document.querySelectorAll(".mobile-nav-link, #mobileExploreBtn").forEach(link => {
  link.addEventListener("click", () => closeDrawer(false));
});

// Close drawer on Escape key and return focus
document.addEventListener("keydown", e => {
  if (e.key === "Escape" && mobileDrawer && mobileDrawer.classList.contains("open")) {
    closeDrawer(true);
  }
});

// Close drawer when screen resizes to desktop width (> 980px)
window.matchMedia("(min-width: 981px)").addEventListener("change", e => {
  if (e.matches) closeDrawer(false);
});

// Lang & Theme Toggles
document.getElementById("langToggle")?.addEventListener("click", toggleLanguage);
document.getElementById("langToggleMobile")?.addEventListener("click", toggleLanguage);
document.getElementById("themeToggle")?.addEventListener("click", toggleTheme);
document.getElementById("themeToggleMobile")?.addEventListener("click", toggleTheme);

// Orbit Nodes Smooth Scroll
document.querySelectorAll(".node").forEach(node => {
  node.addEventListener("click", () => {
    const targetId = node.dataset.target;
    if (targetId) {
      const targetEl = document.getElementById(targetId);
      if (targetEl) {
        targetEl.scrollIntoView({ behavior: "smooth", block: "center" });
        targetEl.classList.add("card-highlight");
        setTimeout(() => targetEl.classList.remove("card-highlight"), 1800);
      }
    }
  });
});

// Central Hub click scrolls to products
document.getElementById("ecosystemHub")?.addEventListener("click", () => {
  document.getElementById("products")?.scrollIntoView({ behavior: "smooth" });
});

// Set current year
const yearEl = document.getElementById("year");
if (yearEl) yearEl.textContent = new Date().getFullYear();

